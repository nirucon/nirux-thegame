fn table() -> &'static [[u8; 8]; 128] {
    static T: OnceLock<[[u8; 8]; 128]> = OnceLock::new();
    T.get_or_init(|| {
        let mut t = [[0u8; 8]; 128];
        for (c, rows) in GLYPHS {
            let mut g = [0u8; 8];
            for (y, r) in rows.iter().enumerate() {
                let mut b = 0u8;
                for (x, ch) in r.bytes().enumerate() {
                    if ch == b'#' {
                        b |= 0x80 >> x;
                    }
                }
                g[y] = b;
            }
            t[*c as usize] = g;
        }
        t
    })
}

/// The bitmap of a character (upper case is used for lower case).
pub fn glyph(c: char) -> [u8; 8] {
    let c = c.to_ascii_uppercase();
    if (c as u32) < 128 {
        table()[c as usize]
    } else {
        table()['?' as usize]
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn glyphs_are_eight_wide_and_cover_the_alphabet() {
        for (c, rows) in GLYPHS {
            for r in rows {
                assert_eq!(r.len(), 8, "glyph {c}");
            }
        }
        for c in ('A'..='Z').chain('0'..='9') {
            assert!(glyph(c).iter().any(|&b| b != 0), "{c}");
        }
        assert_eq!(glyph('a'), glyph('A'));
    }
}
